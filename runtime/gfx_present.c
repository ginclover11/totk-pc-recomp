// The window's Vulkan side, the same on every system: surface, swapchain, present blit, the 60 Hz vsync thread and the
// queue lock. The window itself is gfx_window_win.c or gfx_window_posix.c, behind gfx_window_os.h.
// Swapchain set-up ported from LAS Recomp, runtime/nvn/vulkan/device.c:254-330 (https://github.com/peiikai/LASRecomp @
// da35b83a9611d046a9a681aae668d7085954d37f, MIT, Copyright (c) 2026 Peiikai), SDL replaced by Win32. Focus and vsync
// behaviour from MacNativeGames, games/totk/runtime/frontend.m:88-97, 175-176, 350-352 (https://github.com/ly05010419/
// MacNativeGames @ b75be8cfa704df3701e86130c8ced268e79d6b11, MIT, Copyright (c) 2026 MacNativeGames contributors).
//
// Threads: presents come from any host thread (the back end's present worker) and take g_pl; every queue submission
// takes the recursive queue lock (vk_queue_lock). The vsync thread signals the bound system events. The swapchain is
// rebuilt lazily: a window resize only marks it dirty, the next present (or gfx_window_resize) rebuilds it.
//
// The in-game menu (ui/menu.h) draws over the game image in the present's command buffer, after the blit.
